CREATE TABLE Product
(
    ProductID INT PRIMARY KEY,
    ProductName VARCHAR(100),
    BrandName VARCHAR(50),
    Size VARCHAR(20),
    Color VARCHAR(30),
    Price DECIMAL(10,2),
    Quantity INT,
    CategoryID INT,

    FOREIGN KEY (CategoryID)
    REFERENCES Category(CategoryID)
);



